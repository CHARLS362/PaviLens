export const EN_PATTERNS: [RegExp, string][] = [
  [/^Faltan (\d+) esquinas por marcar\.$/, '$1 corners left to mark.'],
  [/^Perfil horario ilustrativo: valle (.+) y noche (.+) de la demanda punta\.$/, 'Illustrative time profile: off-peak $1 and night $2 of peak demand.'],
  [/^Costo para los usuarios = Δ veh·h por hora × (.+) h × S\/ (.+) por veh·h \(valor referencial; usar el valor social del tiempo vigente del MEF\)\.$/,
    'Cost to road users = Δ veh·h per hour × $1 h × S/ $2 per veh·h (reference value; use the current MEF social value of time).'],
  ...compass('Desvío', 'Detour'),
  ...compass('Alterna', 'Alternative')
];

function compass(es: string, en: string): [RegExp, string][] {
  const heading: Record<string, string> = { norte: 'north', sur: 'south', este: 'east', oeste: 'west' };
  return Object.entries(heading).map(([d, h]) => [new RegExp(`^${es} hacia el ${d}$`), `${en} heading ${h}`]);
}
